/* ============================================================
 *              Low level: command / data over I2C
 * ============================================================ */

/* one command byte: control 0x00 then the command */
static void OLED_Cmd(uint8_t cmd)
{
    uint8_t c = cmd;
    I2C_WriteBuffer(OLED_I2C_ADDR, 0x00, &c, 1);
}

/* burst of data bytes: control 0x40 then the pixels */
static void OLED_DataBurst(const uint8_t *data, uint16_t len)
{
    I2C_WriteBuffer(OLED_I2C_ADDR, 0x40, data, len);
}

/* move the HARDWARE pointer to page + pixel-column */
static void OLED_GotoPixel(uint8_t page, uint8_t pixel_col)
{
    pixel_col += OLED_COL_OFFSET;                  /* SH1106 shift  */
    OLED_Cmd((uint8_t)(0xB0 | (page & 0x07)));     /* page          */
    OLED_Cmd((uint8_t)(0x00 | (pixel_col & 0x0F)));/* col low nib   */
    OLED_Cmd((uint8_t)(0x10 | (pixel_col >> 4)));  /* col high nib  */
}

/* ============================================================
 *                    OLED_Init
 *   NOTE: I2C_Init() must be called BEFORE this function.
 *         This function only configures the display controller.
 * ============================================================ */
void OLED_Init(void)
{
    /* small power-up delay */
    for (volatile uint32_t i = 0; i < 50000; i++);

    OLED_Cmd(0xAE);             /* display OFF                     */
    OLED_Cmd(0xD5); OLED_Cmd(0x80);   /* clock divide ratio        */
    OLED_Cmd(0xA8); OLED_Cmd(0x3F);   /* multiplex = 64            */
    OLED_Cmd(0xD3); OLED_Cmd(0x00);   /* display offset = 0        */
    OLED_Cmd(0x40);             /* start line = 0                  */
    OLED_Cmd(0x8D); OLED_Cmd(0x14);   /* charge pump ON (SSD1306)  */
#ifndef OLED_CONTROLLER_SH1106
    OLED_Cmd(0x20); OLED_Cmd(0x02);   /* PAGE addressing (SSD1306) */
#endif
    OLED_Cmd(0xA1);             /* segment remap (mirror X)        */
    OLED_Cmd(0xC8);             /* COM scan reversed (mirror Y)    */
    OLED_Cmd(0xDA); OLED_Cmd(0x12);   /* COM pins config           */
    OLED_Cmd(0x81); OLED_Cmd(0xCF);   /* contrast                  */
    OLED_Cmd(0xD9); OLED_Cmd(0xF1);   /* pre-charge                */
    OLED_Cmd(0xDB); OLED_Cmd(0x40);   /* VCOMH level               */
    OLED_Cmd(0xA4);             /* display follows RAM             */
    OLED_Cmd(0xA6);             /* normal (not inverted)           */

    OLED_Clear();

    OLED_Cmd(0xAF);             /* display ON                      */
}

/* ============================================================
 *                    OLED_Clear
 * ============================================================ */
void OLED_Clear(void)
{
    uint8_t zeros[16] = {0};

    for (uint8_t page = 0; page < 8; page++)
    {
        OLED_GotoPixel(page, 0);
        for (uint8_t i = 0; i < 128 / 16; i++)   /* 8 bursts x 16 = 128 */
            OLED_DataBurst(zeros, 16);
    }

    cur_row = 0;
    cur_col = 0;
}

/* ============================================================
 *                    Cursor / printing
 * ============================================================ */
void OLED_SetCursor(uint8_t row, uint8_t col)
{
    if (row >= OLED_ROWS) row = OLED_ROWS - 1;
    if (col >= OLED_COLS) col = OLED_COLS - 1;

    cur_row = row;
    cur_col = col;
    OLED_GotoPixel(row, (uint8_t)(col * 6));   /* 6 pixels per char */
}

void OLED_PrintChar(char c)
{
    /* wrap to next line if needed */
    if (cur_col >= OLED_COLS)
    {
        cur_col = 0;
        cur_row = (uint8_t)((cur_row + 1) % OLED_ROWS);
        OLED_GotoPixel(cur_row, 0);
    }

    /* outside the font? print space */
    if (c < 0x20 || c > 0x7E)
        c = ' ';

    /* 5 font columns + 1 blank spacing column */
    uint8_t glyph[6];
    for (uint8_t i = 0; i < 5; i++)
        glyph[i] = font5x7[c - 0x20][i];
    glyph[5] = 0x00;

    OLED_DataBurst(glyph, 6);
    cur_col++;
}

void OLED_PrintString(const char *str)
{
    while (*str)
        OLED_PrintChar(*str++);
}

void OLED_PrintNumber(uint32_t num)
{
    char buf[11];
    int  i = 0;

    if (num == 0) { OLED_PrintChar('0'); return; }

    while (num > 0) {
        buf[i++] = (char)('0' + (num % 10));
        num /= 10;
    }
    while (i > 0)
        OLED_PrintChar(buf[--i]);
}

void OLED_PrintAt(uint8_t row, uint8_t col, const char *str)
{
    OLED_SetCursor(row, col);
    OLED_PrintString(str);
}

void OLED_PrintLine(uint8_t row, const char *str)
{
    OLED_SetCursor(row, 0);

    uint8_t printed = 0;
    while (*str && printed < OLED_COLS) {
        OLED_PrintChar(*str++);
        printed++;
    }
    /* pad the remainder of the line with spaces (wipes old text) */
    while (printed < OLED_COLS) {
        OLED_PrintChar(' ');
        printed++;
    }
}

void OLED_SetContrast(uint8_t value)
{
    OLED_Cmd(0x81);
    OLED_Cmd(value);
}

/* ============================================================
 *                    OLED_Invert
 *   0xA6 = normal (lit pixels on dark), 0xA7 = inverted.
 *   This is the only "colour" control a 1-bit OLED has.
 * ============================================================ */
void OLED_Invert(uint8_t on)
{
    OLED_Cmd(on ? 0xA7 : 0xA6);
}
