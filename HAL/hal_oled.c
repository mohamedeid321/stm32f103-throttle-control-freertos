/**
 ******************************************************************************
 * @file    hal_oled.c
 * @brief   OLED (SSD1306 / SH1106) text driver implementation
 *
 *  I2C protocol of these controllers:
 *    [address][control byte][payload...]
 *      control 0x00 -> the payload is a COMMAND
 *      control 0x40 -> the payload is DATA (pixels)
 *
 *  We use PAGE addressing: the screen is 8 horizontal strips (pages),
 *  each 128 columns x 8 pixels tall. One font character = 6 columns
 *  (5 pixels + 1 spacing), so a page holds 21 characters.
 ******************************************************************************
 */

#include "hal_oled.h"

/* SH1106 RAM is 132 columns; the visible 128 start at column 2 */
#ifdef OLED_CONTROLLER_SH1106
#define OLED_COL_OFFSET  2
#else
#define OLED_COL_OFFSET  0
#endif

